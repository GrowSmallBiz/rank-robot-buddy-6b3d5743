/**
 * Auto-generates public/_redirects from the routes defined in src/App.tsx.
 * Run: node scripts/generate-redirects.js
 * Called automatically during build via package.json "build" script.
 */

const fs = require('fs');
const path = require('path');

const appFile = fs.readFileSync(path.resolve(__dirname, '../src/App.tsx'), 'utf-8');

// Extract all path strings from route definitions
const pathRegex = /path:\s*["']([^"'*]+)["']/g;
const routes = [];
let match;

while ((match = pathRegex.exec(appFile)) !== null) {
  const route = match[1];
  // Skip index-like paths, catch-all, and paths that are just "/"
  if (route && route !== '/' && route !== '404') {
    routes.push('/' + route.replace(/^\//, ''));
  }
}

// Deduplicate
const uniqueRoutes = [...new Set(routes)];

let output = `# Auto-generated by scripts/generate-redirects.js — do not edit manually\n`;
output += `# Trailing slash redirects to prevent 308 redirects and duplicate pages\n\n`;

for (const route of uniqueRoutes.sort()) {
  output += `${route}/    ${route}    301\n`;
}

output += `\n# SPA fallback\n/*  /index.html  200\n`;

const outPath = path.resolve(__dirname, '../public/_redirects');
fs.writeFileSync(outPath, output, 'utf-8');
console.log(`✅ Generated _redirects with ${uniqueRoutes.length} trailing-slash rules`);
