/**
 * Auto-generates public/_redirects.
 * Run: node scripts/generate-redirects.cjs
 * Called automatically during build via package.json "build" script.
 *
 * NOTE: SPA fallback is handled natively by Cloudflare Pages.
 * SSG pre-renders all routes, so no catch-all redirect is needed.
 */

const fs = require('fs');
const path = require('path');

let output = `# Auto-generated by scripts/generate-redirects.cjs — do not edit manually\n`;
output += `# Redirects managed via Cloudflare Redirect Rules\n`;
output += `# SPA fallback is handled natively by Cloudflare Pages\n`;

// Hard 301s served by Cloudflare Pages. Any path listed here MUST be excluded
// from SSG pre-rendering in vite.config.ts (PRERENDER_EXCLUDE), because a
// static asset takes precedence over a _redirects rule.
const HARD_301 = [
  ['/workshops/in-person/', '/workshops/ai-visibility-in-person/'],
  ['/workshops/in-person', '/workshops/ai-visibility-in-person/'],
];
output += `\n`;
for (const [from, to] of HARD_301) output += `${from} ${to} 301\n`;

const outPath = path.resolve(__dirname, '../public/_redirects');
fs.writeFileSync(outPath, output, 'utf-8');
console.log('✅ Generated _redirects (no SPA fallback — handled by Cloudflare Pages natively)');
