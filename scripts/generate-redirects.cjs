/**
 * Auto-generates public/_redirects.
 * Run: node scripts/generate-redirects.cjs
 * Called automatically during build via package.json "build" script.
 *
 * NOTE: With Vite SSG dirStyle="nested" + Cloudflare, forcing slash->no-slash
 * redirects can create infinite 308<->301 loops on custom domains.
 */

const fs = require('fs');
const path = require('path');

let output = `# Auto-generated by scripts/generate-redirects.cjs — do not edit manually\n`;
output += `# Keep only SPA fallback to avoid Cloudflare trailing-slash redirect loops\n\n`;
output += `# SPA fallback\n/*  /index.html  200\n`;

const outPath = path.resolve(__dirname, '../public/_redirects');
fs.writeFileSync(outPath, output, 'utf-8');
console.log('✅ Generated _redirects with SPA fallback only (no slash normalization rules)');